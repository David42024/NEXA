/**
 * Normaliza un nombre geografico para hacer join con GeoJSON externo.
 * Quita tildes, pasa a mayusculas, elimina espacios extra.
 */
export function normalizarNombre(nombre) {
  if (!nombre) return ''
  return nombre
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/\s+/g, ' ')
    .trim()
}

